#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Generate Rust code for the LibrePCB RPC API.

This script generates `libs/librepcb/rust-core/src/rpc_server/api_gen.rs`
from the RPC API specification `share/librepcb/rpc/rpc.yml` (the single
source of truth). For now it contains the error codes (with their
canonical messages); more parts of the API may follow later. The
generated file is committed to the repository, so building does not
require Python.

Usage:

    python3 dev/generate_rpc_api_code.py    # Generate the code
"""

import pathlib
import re
import sys

import yaml

REPO_DIR = pathlib.Path(__file__).parent.parent
SPEC_FILE = REPO_DIR / "share" / "librepcb" / "rpc" / "rpc.yml"
OUT_FILE = (
    REPO_DIR / "libs" / "librepcb" / "rust-core" / "src" / "rpc_server" / "api_gen.rs"
)

HEADER = """\
//! GENERATED FILE — do not edit manually!
//!
//! Generated by `dev/generate_rpc_api_code.py` from
//! `share/librepcb/rpc/rpc.yml`. Regenerate and commit this file after
//! changing the specification.
"""


def rust_comment(text, prefix="///"):
    """Wrap a text into a Rust doc comment (ca. 80 columns)."""
    text = re.sub(r"\s+", " ", text).strip()
    lines = []
    line = prefix
    for word in text.split(" "):
        if len(line) + 1 + len(word) > 80:
            lines.append(line)
            line = prefix
        line += " " + word
    lines.append(line)
    return "\n".join(lines)


def rust_string(s):
    """Escape a string into a Rust string literal."""
    return '"{}"'.format(s.replace("\\", "\\\\").replace('"', '\\"'))


def main():
    with open(SPEC_FILE, "r") as f:
        spec = yaml.safe_load(f)

    errors = spec["error_types"]

    lines = [HEADER, ""]
    lines.append(rust_comment(
        "Error codes for the RPC protocol, as listed in the error types"
        " section of the API specification. The codes are grouped:"
        " 10-19 transport errors, 20-29 protocol errors, 30-39 command"
        " errors, 100- command execution errors. Also used by the C++"
        " side (see `rpcserver.h`)."))
    lines.append("#[derive(Clone, Copy, Debug, Eq, PartialEq)]")
    lines.append("#[repr(i32)]")
    lines.append("pub enum RpcErrorCode {")
    for error in errors:
        lines.append(rust_comment(error["description"]))
        lines.append(f"  {error['name']} = {error['code']},")
    lines.append("}")
    lines.append("")
    lines.append("impl RpcErrorCode {")
    lines.append("  /// The canonical error message, as sent on the wire if")
    lines.append("  /// the application does not provide a more specific one.")
    lines.append("  pub const fn message(self) -> &'static str {")
    lines.append("    match self {")
    for error in errors:
        lines.append(
            f"      Self::{error['name']} => {rust_string(error['message'])},")
    lines.append("    }")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    lines.append("impl TryFrom<i32> for RpcErrorCode {")
    lines.append("  type Error = ();")
    lines.append("")
    lines.append("  fn try_from(code: i32) -> Result<Self, Self::Error> {")
    lines.append("    match code {")
    for error in errors:
        lines.append(f"      {error['code']} => Ok(Self::{error['name']}),")
    lines.append("      _ => Err(()),")
    lines.append("    }")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    OUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUT_FILE}")


if __name__ == "__main__":
    sys.exit(main())
