/// Maximum time [RpcServer::stop] waits for connection threads to finish. A
/// thread which is currently blocked inside the dispatch callback cannot be
/// interrupted, so after this timeout it is detached with a warning (which
/// is fine during application teardown).
const STOP_TIMEOUT: Duration = Duration::from_secs(5);

/// Callback which handles a command request.
///
/// It receives the method name (e.g. `"project/list"`) and the raw JSON of
/// the request parameters (a valid JSON document, or `"null"` if the request
/// contained no params), and returns either the raw JSON of the result (any
/// valid JSON document) or an [RpcError]. The JSON content is completely
/// opaque to this server module, so the handler has full control over it.
///
/// The callback is invoked on the connection's reader thread, i.e. possibly
/// concurrently from multiple threads, but strictly sequentially per
/// connection.
pub type DispatchFn =
  Arc<dyn Fn(&str, &str) -> Result<String, RpcError> + Send + Sync>;

/// Configuration for creating a [RpcServer].
pub struct RpcServerConfig {
  /// Authentication token which clients must provide in their `initialize`
  /// request. Intentionally not generated here, since in the LibrePCB
  /// application it is generated by the C++ side (which also stores it in a
  /// file with restricted permissions). Must not be empty.
  pub token: String,
  /// Protocol version, reported in the `initialize` response. Clients use
  /// it to detect compatibility.
  pub protocol_version: String,
  /// Additional application information (a JSON object) which is merged
  /// into the `initialize` response, e.g. the application version, the PID
  /// or the workspace path. A `protocolVersion` key is always overwritten
  /// by the [RpcServer], all other keys are passed through as-is. If this is
  /// not a JSON object, it is ignored.
  pub info: Value,
  /// Callback which handles all commands not handled by the server itself.
  pub dispatch: DispatchFn,
}

/// Internal shared state of the [RpcServer], used by all its threads.
struct Inner {
  /// The configuration as passed to [RpcServer::new].
  config: RpcServerConfig,
  /// The OpenRPC schema document served by the `rpc.discover` method, if
  /// any.
  api_schema: Mutex<Option<String>>,
  /// Registered connections, by connection ID.
  clients: Mutex<HashMap<u64, Connection>>,
  /// Whether the server is running (set to `false` by [RpcServer::stop]).
  running: AtomicBool,
  /// Number of currently active connections (reader threads).
  active_connections: AtomicUsize,
  /// Generator for connection IDs.
  next_conn_id: AtomicU64,
  /// The handle of the accept loop thread, if the server was started.
  accept_thread: Mutex<Option<JoinHandle<()>>>,
}

/// A registered connection, used to push messages to it and to shut it
/// down.
struct Connection {
  /// Channel to the connection's writer thread.
  tx: Sender<String>,
  /// Clone of the connection's socket, used to shut it down when stopping
  /// the server (which unblocks both the reader and the writer thread).
  stream: TcpStream,
}

/// The RPC server.
///
/// Usage: Create it with [RpcServer::new], optionally set the API schema with
/// [RpcServer::set_api_schema], then call [RpcServer::start] to make it listen on
/// 127.0.0.1 (the OS assigns the port, which is returned). Push events to
/// all connected clients with [RpcServer::notify], and shut the server down
/// with [RpcServer::stop] (or just drop it, which does the same).
///
/// All methods can be called from any thread. The dispatch callback is
/// invoked on the connection's reader thread.
pub struct RpcServer {
  /// The state shared between the server and all its threads.
  inner: Arc<Inner>,
}

impl RpcServer {
  /// Create a new server (not started yet).
  pub fn new(config: RpcServerConfig) -> Self {
    Self {
      inner: Arc::new(Inner {
        config,
        api_schema: Mutex::new(None),
        clients: Mutex::new(HashMap::new()),
        running: AtomicBool::new(false),
        active_connections: AtomicUsize::new(0),
        next_conn_id: AtomicU64::new(0),
        accept_thread: Mutex::new(None),
      }),
    }
  }

  /// Set (or clear) the OpenRPC API schema document served by the
  /// `rpc.discover` method.
  ///
  /// Must be a valid JSON document, otherwise `rpc.discover` responds with
  /// an internal error.
  pub fn set_api_schema(&self, schema: Option<String>) {
    *lock(&self.inner.api_schema) = schema;
  }

  /// Start listening on 127.0.0.1, with the port assigned by the OS.
  ///
  /// Returns the chosen port, which the caller needs to make the server
  /// discoverable for clients. Returns an error if the server is already
  /// running or if the token is empty.
  pub fn start(&self) -> io::Result<u16> {
    self.start_on_port(0)
  }

  /// Start listening on 127.0.0.1 on the given port (0 = OS-assigned).
  ///
  /// Returns the chosen port, which the caller needs to make the server
  /// discoverable for clients. Returns an error if the server is already
  /// running or if the token is empty.
  pub fn start_on_port(&self, port: u16) -> io::Result<u16> {
    if self.inner.config.token.is_empty() {
      return Err(io::Error::new(io::ErrorKind::InvalidInput, "empty token"));
    }
    if self.inner.running.load(Ordering::SeqCst) {
      return Err(io::Error::new(
        io::ErrorKind::InvalidInput,
        "server is already running",
      ));
    }
    let listener = TcpListener::bind(("127.0.0.1", port))?;
    listener.set_nonblocking(true)?;
    let port = listener.local_addr()?.port();
    self.inner.running.store(true, Ordering::SeqCst);
    let inner = self.inner.clone();
    let handle = thread::Builder::new()
      .name("rpc-accept".to_string())
      .spawn(move || connection::accept_loop(inner, listener))?;
    *lock(&self.inner.accept_thread) = Some(handle);
    Ok(port)
  }

  /// Push an event (a JSON-RPC notification) to all connected clients.
  ///
  /// `params` must be a valid JSON document (or empty, which is treated as
  /// `null`). Invalid JSON is ignored with a warning, since such an event
  /// can't be delivered without breaking the protocol. This method never
  /// blocks (the message is just queued on each connection) and thus may
  /// safely be called while a command dispatch is in progress.
  pub fn notify(&self, method: &str, params: &str) {
    let params = if params.trim().is_empty() {
      Value::Null
    } else {
      match serde_json::from_str(params) {
        Ok(value) => value,
        Err(e) => {
          eprintln!("librepcb-rust: Ignoring event with invalid params: {e}");
          return;
        }
      }
    };
    let message = build_notification(method, &params);
    let mut clients = lock(&self.inner.clients);
    let mut dead = Vec::new();
    for (id, client) in clients.iter() {
      if client.tx.send(message.clone()).is_err() {
        dead.push(*id);
      }
    }
    for id in dead {
      clients.remove(&id);
    }
  }

  /// Stop the server.
  ///
  /// Closes the listener and all client sockets and waits (up to 5 seconds)
  /// for the connection threads to finish. A thread which is currently
  /// blocked inside the dispatch callback cannot be interrupted, so after
  /// the timeout it is detached with a warning (which is fine during
  /// application teardown). Calling this on a stopped server is a no-op.
  pub fn stop(&self) {
    self.inner.running.store(false, Ordering::SeqCst);
    // The accept loop polls the running flag, so it (and thus also this
    // join) returns within ~10 ms. It must not be running when the client
    // sockets are shut down below, otherwise new connections could sneak
    // in between.
    if let Some(handle) = lock(&self.inner.accept_thread).take() {
      let _ = handle.join();
    }
    // Shutting down the sockets unblocks the reader threads (EOF) and the
    // writer threads (write error or closed channel).
    {
      let mut clients = lock(&self.inner.clients);
      for client in clients.values() {
        let _ = client.stream.shutdown(Shutdown::Both);
      }
      clients.clear();
    }
    let deadline = Instant::now() + STOP_TIMEOUT;
    while self.inner.active_connections.load(Ordering::SeqCst) > 0 {
      if Instant::now() >= deadline {
        eprintln!(
          "librepcb-rust: Detaching connection threads which are still busy"
        );
        break;
      }
      thread::sleep(Duration::from_millis(10));
    }
  }
}

impl Drop for RpcServer {
  fn drop(&mut self) {
    self.stop();
  }
}

/// Lock a mutex, ignoring a poisoned state (a panic in another thread
/// doesn't justify failing the whole server).
fn lock<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
  mutex.lock().unwrap_or_else(|e| e.into_inner())
}

