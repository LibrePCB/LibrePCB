  #[test]
  fn test_rpc_discover() {
    let (server, port) = spawn_server();
    let mut client = TestClient::new(port);
    // Without a schema, the method is not available:
    let response = client.request("1", "rpc.discover", "null");
    assert_eq!(
      response.get("error").unwrap().get("code"),
      Some(&json!(error_code::METHOD_NOT_FOUND))
    );
    // With a schema, it is served as-is:
    let schema = r#"{"openrpc":"1.2.6","info":{"title":"t"},"methods":[]}"#;
    server.set_api_schema(Some(schema.to_string()));
    let response = client.request("2", "rpc.discover", "null");
    assert_eq!(
      response.get("result"),
      Some(&serde_json::from_str::<Value>(schema).unwrap())
    );
  }

