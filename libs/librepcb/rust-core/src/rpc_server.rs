  /// A TCP client connected to the test server.
  struct TestClient {
    reader: BufReader<TcpStream>,
    writer: TcpStream,
  }

  impl TestClient {
    /// Connect without authenticating.
    fn new_unauthenticated(port: u16) -> Self {
      let stream = TcpStream::connect(("127.0.0.1", port)).unwrap();
      // Timeout to avoid hanging forever (and thus blocking CI) if the
      // server does not respond.
      stream
        .set_read_timeout(Some(Duration::from_secs(10)))
        .unwrap();
      Self {
        reader: BufReader::new(stream.try_clone().unwrap()),
        writer: stream,
      }
    }

    /// Connect and authenticate.
    fn new(port: u16) -> Self {
      let mut client = Self::new_unauthenticated(port);
      let response = client.initialize(TOKEN);
      assert!(response.get("result").is_some(), "initialize failed");
      client
    }

    /// Send a raw message.
    fn send(&mut self, message: &str) {
      use std::io::Write;
      self.writer.write_all(message.as_bytes()).unwrap();
      self.writer.write_all(b"\n").unwrap();
      self.writer.flush().unwrap();
    }

    /// Send a request and return the parsed response.
    fn request(&mut self, id: &str, method: &str, params: &str) -> Value {
      self.send(&format!(
        r#"{{"jsonrpc":"2.0","id":{id},"method":"{method}","params":{params}}}"#
      ));
      self.read_message()
    }

    /// Read one message (blocking, with timeout).
    fn read_message(&mut self) -> Value {
      use std::io::BufRead;
      let mut line = String::new();
      let size = self.reader.read_line(&mut line).expect("read response");
      assert!(size > 0, "the connection was closed unexpectedly");
      serde_json::from_str(&line).unwrap()
    }

    /// Read the next message, expecting EOF (the server closed the
    /// connection).
    fn read_eof(&mut self) {
      use std::io::BufRead;
      let mut line = String::new();
      let size = self.reader.read_line(&mut line).expect("read EOF");
      assert_eq!(size, 0, "the connection is still open");
    }

    /// Send an `initialize` request with the given token.
    fn initialize(&mut self, token: &str) -> Value {
      self.request("1", "initialize", &format!(r#"{{"token":"{token}"}}"#))
    }
  }

  /// Create a started test server with a dispatch handler which just
  /// echoes the method and params.
  fn spawn_server() -> (RpcServer, u16) {
    let dispatch: DispatchFn = Arc::new(|method, params| {
      Ok(format!(r#"{{"method":"{method}","params":{params}}}"#))
    });
    spawn_server_with_dispatch(dispatch)
  }

  /// Create a started test server with a custom dispatch handler.
  fn spawn_server_with_dispatch(dispatch: DispatchFn) -> (RpcServer, u16) {
    let server = RpcServer::new(RpcServerConfig {
      token: TOKEN.to_string(),
      protocol_version: "1".to_string(),
      info: json!({"appVersion": "0.1.0"}),
      dispatch,
    });
    let port = server.start().unwrap();
    (server, port)
  }

