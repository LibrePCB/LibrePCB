  #[test]
  fn test_dispatch_on_multiple_connections_is_concurrent() {
    // The reader threads of different connections dispatch concurrently
    // (only within one connection, requests are strictly sequential).
    let active = Arc::new(AtomicUsize::new(0));
    let max_active = Arc::new(AtomicUsize::new(0));
    let dispatch: DispatchFn = {
      let active = active.clone();
      let max_active = max_active.clone();
      Arc::new(move |_, _| {
        let count = active.fetch_add(1, Ordering::SeqCst) + 1;
        max_active.fetch_max(count, Ordering::SeqCst);
        thread::sleep(Duration::from_millis(300));
        active.fetch_sub(1, Ordering::SeqCst);
        Ok("null".to_string())
      })
    };
    let (_server, port) = spawn_server_with_dispatch(dispatch);
    let mut client1 = TestClient::new(port);
    let mut client2 = TestClient::new(port);
    // Start a slow request on connection 1, then one on connection 2:
    client1.send(r#"{"jsonrpc":"2.0","id":1,"method":"a/b","params":null}"#);
    client2.send(r#"{"jsonrpc":"2.0","id":1,"method":"a/b","params":null}"#);
    assert!(client1.read_message().get("result").is_some());
    assert!(client2.read_message().get("result").is_some());
    // The 300 ms delays overlapped, i.e. the dispatches were concurrent:
    assert!(max_active.load(Ordering::SeqCst) >= 2);
  }

