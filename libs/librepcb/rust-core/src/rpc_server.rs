//! TCP RPC server for external tools.
//!
//! This module implements a [JSON-RPC 2.0] server listening on a local TCP
//! socket (127.0.0.1, port assigned by the OS). It is intended to be the
//! single entry point for external tools which want to interact with a
//! running LibrePCB instance, e.g. an MCP server, plugins or scripting
//! libraries. All those tools are just clients of this one server.
//!
//! # Architecture
//!
//! * The whole protocol handling (framing, authentication, request/response
//!   envelope) is done here in pure Rust, without any dependency to Qt or
//!   the C++ part of LibrePCB.
//! * Commands are dispatched through a [DispatchFn] callback. In the
//!   LibrePCB application this callback is implemented in C++ (through the
//!   FFI, to be added in `ffi/rpc_server_ffi.rs`) and marshals each command to
//!   the GUI thread, so command handlers can safely access editor state.
//!   For tests, a simple closure is sufficient.
//! * Events can be pushed to all connected clients with [RpcServer::notify],
//!   as JSON-RPC notifications.
//! * A connection must first be authenticated by sending an `initialize`
//!   request containing the correct token. Until then, any other message
//!   leads to an error response and an immediate disconnect.
//! * The OpenRPC API schema document can be provided with
//!   [RpcServer::set_api_schema] and is then served by the standard
//!   `rpc.discover` method, so clients can discover the API at runtime.
//!
//! # Threading Model
//!
//! No async runtime is used, just plain std threads (the number of local
//! clients is small, so this is by far the simplest and most maintainable
//! option):
//!
//! * The accept loop runs on its own thread, polling the non-blocking
//!   listener. This makes it trivially interruptible on every platform
//!   when stopping the server.
//! * Each connection consists of two threads: A reader thread which blocks
//!   on reading messages and dispatches them, and a writer thread which
//!   blocks on a channel receiving responses and notifications to send.
//!   This decouples blocking writes from reading, and allows other threads
//!   to push notifications at any time.
//! * Requests on a single connection are processed strictly sequentially,
//!   i.e. the reader thread blocks until a request was fully dispatched.
//!   Clients which want to run commands in parallel need to open multiple
//!   connections. This matches the fact that on the C++ side, all commands
//!   will be serialized on the GUI thread anyway.
//!
//! # Module Structure
//!
//! * `protocol`: The JSON-RPC 2.0 message envelope (classification and
//!   serialization).
//! * `codec`: The newline-delimited JSON framing.
//! * `connection`: The accept loop and the per-connection threads.
//!
//! [JSON-RPC 2.0]: https://www.jsonrpc.org/specification

